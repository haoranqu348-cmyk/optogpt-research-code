def replace_paragraph_text(paragraph, new_text: str) -> None:
    """Replace text while preserving paragraph properties and the first run's style."""
    if paragraph._p.xpath(".//w:drawing | .//w:pict"):
        raise ValueError("Refusing to replace a paragraph containing an image")

    template_rpr = None
    for run in paragraph.runs:
        if run._r.rPr is not None:
            template_rpr = deepcopy(run._r.rPr)
            break

    for run in list(paragraph.runs):
        paragraph._p.remove(run._r)

    run = paragraph.add_run(new_text)
    if template_rpr is not None:
        if run._r.rPr is not None:
            run._r.remove(run._r.rPr)
        run._r.insert(0, template_rpr)

    # Explicitly mark the translated text as Simplified Chinese for Word.
    rpr = run._r.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.insert(0, rfonts)
    # Hiragino Sans GB is a standard Simplified Chinese font on macOS and is
    # available to the local LibreOffice renderer.
    for script in ("ascii", "hAnsi", "eastAsia", "cs"):
        rfonts.set(qn(f"w:{script}"), "Hiragino Sans GB")
    lang = rpr.find(qn("w:lang"))
    if lang is None:
        lang = OxmlElement("w:lang")
        rpr.append(lang)
    lang.set(qn("w:eastAsia"), "zh-CN")


def main() -> None:
    document = Document(SOURCE)
    nonempty = {i for i, p in enumerate(document.paragraphs) if p.text.strip()}
    missing = sorted(nonempty - set(TRANSLATIONS))
    extra = sorted(set(TRANSLATIONS) - nonempty)
    if missing or extra:
        raise RuntimeError(f"Translation map mismatch: missing={missing}, extra={extra}")

    for index, translated in TRANSLATIONS.items():
        replace_paragraph_text(document.paragraphs[index], translated)

    for index, description in IMAGE_ALT_TEXT.items():
        paragraph = document.paragraphs[index]
        doc_properties = paragraph._p.xpath(".//wp:docPr")
        if not doc_properties:
            raise RuntimeError(f"Expected image metadata in paragraph {index}")
        for doc_property in doc_properties:
            doc_property.set("descr", description)
            doc_property.set("title", description)

    document.core_properties.title = "双条件 GPT 逆设计（完整中文翻译）"
    document.core_properties.subject = "OptoGPT 双偏振逆向设计中文译文"
    document.save(OUTPUT)
    print(OUTPUT.resolve())


if __name__ == "__main__":
    main()
